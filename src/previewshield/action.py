"""Secure GitHub Action adapter for the PreviewShield CLI.

The adapter deliberately invokes :mod:`previewshield.cli` in-process with an
argument list.  No user-provided value is ever interpreted by a shell.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import secrets
import sys
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import cast

from previewshield import cli as previewshield_cli

ACTION_USAGE_ERROR = 2
MAX_JSON_REPORT_BYTES = 50_000_000
MAX_SUMMARY_CHARACTERS = 200_000
SUPPORTED_FORMATS = frozenset({"json", "markdown", "sarif"})
_OUTPUT_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_-]*\Z")

CliMain = Callable[[Sequence[str] | None], int | None]


class ActionInputError(ValueError):
    """Raised when GitHub Action inputs describe an ambiguous invocation."""


@dataclass(frozen=True)
class ActionInputs:
    """Normalized and validated GitHub Action inputs."""

    target: str | None
    baseline: str | None
    preview: str | None
    config: str | None
    paths: tuple[str, ...]
    fail_on: str
    report_format: str
    output: Path
    allow_private: bool

    @classmethod
    def from_values(  # noqa: PLR0913 - mirrors the public action input contract
        cls,
        *,
        target: str = "",
        baseline: str = "",
        preview: str = "",
        config: str = "",
        paths: str = "",
        fail_on: str = "high",
        report_format: str = "json",
        output: str = "",
        allow_private: str = "false",
    ) -> ActionInputs:
        """Normalize strings supplied by action metadata or the environment."""

        normalized_target = _optional(target)
        normalized_baseline = _optional(baseline)
        normalized_preview = _optional(preview)

        if normalized_target and (normalized_baseline or normalized_preview):
            raise ActionInputError("Use target or baseline+preview, not both.")
        if not normalized_target and not (normalized_baseline or normalized_preview):
            raise ActionInputError("Provide target or both baseline and preview.")
        if bool(normalized_baseline) is not bool(normalized_preview):
            raise ActionInputError("Baseline and preview must be provided together.")

        normalized_format = report_format.strip().lower() or "json"
        if normalized_format == "md":
            normalized_format = "markdown"
        if normalized_format not in SUPPORTED_FORMATS:
            allowed = ", ".join(sorted(SUPPORTED_FORMATS))
            raise ActionInputError(f"Unsupported format '{normalized_format}'. Use: {allowed}.")

        default_output = {
            "json": "previewshield-report.json",
            "markdown": "previewshield-report.md",
            "sarif": "previewshield-report.sarif",
        }[normalized_format]
        normalized_output = output.strip() or default_output
        if any(character in normalized_output for character in ("\x00", "\r", "\n")):
            raise ActionInputError("Output must be a single valid filesystem path.")

        normalized_fail_on = fail_on.strip().lower() or "high"
        return cls(
            target=normalized_target,
            baseline=normalized_baseline,
            preview=normalized_preview,
            config=_optional(config),
            paths=_split_paths(paths),
            fail_on=normalized_fail_on,
            report_format=normalized_format,
            output=Path(normalized_output),
            allow_private=_parse_boolean(allow_private),
        )

    @classmethod
    def from_environment(cls, environ: Mapping[str, str]) -> ActionInputs:
        """Read the conventional ``INPUT_*`` variables exposed by GitHub."""

        return cls.from_values(
            target=environ.get("INPUT_TARGET", ""),
            baseline=environ.get("INPUT_BASELINE", ""),
            preview=environ.get("INPUT_PREVIEW", ""),
            config=environ.get("INPUT_CONFIG", ""),
            paths=environ.get("INPUT_PATHS", ""),
            fail_on=environ.get("INPUT_FAIL_ON", environ.get("INPUT_FAIL-ON", "high")),
            report_format=environ.get("INPUT_FORMAT", "json"),
            output=environ.get("INPUT_OUTPUT", ""),
            allow_private=environ.get(
                "INPUT_ALLOW_PRIVATE", environ.get("INPUT_ALLOW-PRIVATE", "false")
            ),
        )


@dataclass(frozen=True)
class OutputPlan:
    """Locations for the three reports generated by one CLI invocation."""

    json: Path
    markdown: Path
    sarif: Path
    exposed: Path


@dataclass(frozen=True)
class ReportMetadata:
    """Small report subset exposed as GitHub Action outputs."""

    score: str
    grade: str
    passed: bool


def _optional(value: str) -> str | None:
    normalized = value.strip()
    return normalized or None


def _split_paths(value: str) -> tuple[str, ...]:
    """Accept convenient comma-separated or multiline route inputs."""

    return tuple(part.strip() for part in re.split(r"[,\r\n]+", value) if part.strip())


def _parse_boolean(value: str) -> bool:
    normalized = value.strip().lower()
    if normalized in {"1", "true", "yes", "on"}:
        return True
    if normalized in {"0", "false", "no", "off", ""}:
        return False
    raise ActionInputError(f"allow-private must be true or false, not '{value}'.")


def build_output_plan(report_format: str, output: Path) -> OutputPlan:
    """Map the selected public report to collision-free sidecar paths."""

    known_suffixes = {".json", ".md", ".markdown", ".sarif"}
    base = output.with_suffix("") if output.suffix.lower() in known_suffixes else output
    defaults = {
        "json": Path(f"{base}.json"),
        "markdown": Path(f"{base}.md"),
        "sarif": Path(f"{base}.sarif"),
    }
    candidates = {report_format: output}
    used = {output}
    for name in ("json", "markdown", "sarif"):
        if name == report_format:
            continue
        candidate = defaults[name]
        if candidate in used:
            extension = {"json": ".json", "markdown": ".md", "sarif": ".sarif"}[name]
            candidate = Path(f"{output}.previewshield{extension}")
        candidates[name] = candidate
        used.add(candidate)

    return OutputPlan(
        json=candidates["json"],
        markdown=candidates["markdown"],
        sarif=candidates["sarif"],
        exposed=output,
    )


def build_cli_argv(inputs: ActionInputs, outputs: OutputPlan) -> list[str]:
    """Translate action inputs into the public CLI contract without a shell."""

    if inputs.target is not None:
        argv = ["scan", inputs.target]
    else:
        if inputs.baseline is None or inputs.preview is None:
            raise ActionInputError("Diff mode requires both baseline and preview.")
        argv = ["diff", "--baseline", inputs.baseline, "--preview", inputs.preview]

    if inputs.config is not None:
        argv.extend(("--config", inputs.config))
    for route in inputs.paths:
        argv.extend(("--path", route))
    argv.extend(
        (
            "--fail-on",
            inputs.fail_on,
            "--format",
            "json",
            "--output",
            str(outputs.json),
            "--also-format",
            f"markdown={outputs.markdown}",
            "--also-format",
            f"sarif={outputs.sarif}",
        )
    )
    if inputs.allow_private:
        argv.append("--allow-private")
    return argv


def invoke_cli(cli_main: CliMain, argv: Sequence[str]) -> int:
    """Invoke a ``main(argv)`` function and normalize its exit convention."""

    try:
        result = cli_main(list(argv))
    except SystemExit as error:
        if error.code is None:
            return 0
        if isinstance(error.code, int):
            return error.code
        return ACTION_USAGE_ERROR
    if result is None:
        return 0
    if not isinstance(result, int):
        raise TypeError("previewshield.cli.main(argv) must return int or None.")
    return result


def load_report(path: Path) -> Mapping[str, object] | None:
    """Load a generated JSON report, returning ``None`` when it is unavailable."""

    try:
        if path.stat().st_size > MAX_JSON_REPORT_BYTES:
            return None
        with path.open(encoding="utf-8") as report_file:
            raw: object = json.load(report_file)
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(raw, dict):
        return None
    return cast(dict[str, object], raw)


def extract_report_metadata(
    payload: Mapping[str, object] | None, *, exit_code: int
) -> ReportMetadata:
    """Extract scan or diff metadata while retaining sensible failure defaults."""

    if payload is None:
        return ReportMetadata(score="", grade="", passed=exit_code == 0)

    preview = payload.get("preview")
    score_source = cast(Mapping[str, object], preview) if isinstance(preview, Mapping) else payload
    score = _scalar_output(score_source.get("score"))
    grade = _scalar_output(score_source.get("grade"))
    raw_passed = payload.get("passed")
    passed = raw_passed if isinstance(raw_passed, bool) else exit_code == 0
    return ReportMetadata(score=score, grade=grade, passed=passed)


def _scalar_output(value: object) -> str:
    if isinstance(value, bool) or value is None:
        return ""
    if isinstance(value, (int, float, str)):
        return str(value)
    return ""


def write_github_outputs(path: Path, values: Mapping[str, str]) -> None:
    """Append injection-safe multiline values to ``GITHUB_OUTPUT``."""

    with path.open("a", encoding="utf-8", newline="\n") as output_file:
        for name, value in values.items():
            if _OUTPUT_NAME.fullmatch(name) is None:
                raise ValueError(f"Invalid GitHub output name: {name!r}.")
            delimiter = f"PREVIEWSHIELD_{secrets.token_hex(16)}"
            while delimiter in value:
                delimiter = f"PREVIEWSHIELD_{secrets.token_hex(16)}"
            output_file.write(f"{name}<<{delimiter}\n{value}\n{delimiter}\n")


def build_fallback_summary(metadata: ReportMetadata, report: Path) -> str:
    """Build a concise summary when the Markdown reporter could not run."""

    status = "Passed" if metadata.passed else "Failed"
    score = _markdown_text(metadata.score or "Unavailable")
    grade = _markdown_text(metadata.grade or "Unavailable")
    report_path = _markdown_text(str(report))
    return (
        "# PreviewShield\n\n"
        f"- Status: **{status}**\n"
        f"- Score: **{score}**\n"
        f"- Grade: **{grade}**\n"
        f"- Report: `{report_path}`\n"
    )


def _markdown_text(value: str) -> str:
    return value.replace("\\", "\\\\").replace("`", "\\`").replace("\r", " ").replace("\n", " ")


def read_markdown_summary(path: Path) -> str | None:
    """Read a bounded Markdown report suitable for ``GITHUB_STEP_SUMMARY``."""

    try:
        with path.open(encoding="utf-8") as summary_file:
            content = summary_file.read(MAX_SUMMARY_CHARACTERS + 1)
    except (OSError, UnicodeError):
        return None
    if len(content) > MAX_SUMMARY_CHARACTERS:
        content = content[:MAX_SUMMARY_CHARACTERS]
        content += "\n\n_Report truncated by the PreviewShield Action._\n"
    return content


def append_step_summary(path: Path, markdown: str) -> None:
    """Append Markdown to the current job summary file."""

    with path.open("a", encoding="utf-8", newline="\n") as summary_file:
        summary_file.write(markdown)
        if not markdown.endswith("\n"):
            summary_file.write("\n")


def run_action(
    inputs: ActionInputs,
    *,
    cli_main: CliMain | None = None,
    environ: Mapping[str, str] | None = None,
) -> int:
    """Run PreviewShield, publish action metadata, and preserve the CLI exit code."""

    environment = os.environ if environ is None else environ
    outputs = build_output_plan(inputs.report_format, inputs.output)
    argv = build_cli_argv(inputs, outputs)
    exit_code = invoke_cli(previewshield_cli.main if cli_main is None else cli_main, argv)

    # Exit codes 2+ cannot have a valid fresh scan report. Ignoring any file at
    # that path prevents stale workspace artifacts from publishing false success.
    payload = load_report(outputs.json) if exit_code in {0, 1} else None
    metadata = extract_report_metadata(payload, exit_code=exit_code)
    github_output = environment.get("GITHUB_OUTPUT")
    if github_output:
        try:
            write_github_outputs(
                Path(github_output),
                {
                    "report": str(outputs.exposed),
                    "score": metadata.score,
                    "grade": metadata.grade,
                    "passed": str(metadata.passed).lower(),
                },
            )
        except OSError as error:
            print(f"PreviewShield could not write GITHUB_OUTPUT: {error}", file=sys.stderr)

    github_summary = environment.get("GITHUB_STEP_SUMMARY")
    if github_summary:
        markdown = read_markdown_summary(outputs.markdown)
        if markdown is None:
            markdown = build_fallback_summary(metadata, outputs.exposed)
        try:
            append_step_summary(Path(github_summary), markdown)
        except OSError as error:
            print(f"PreviewShield could not write GITHUB_STEP_SUMMARY: {error}", file=sys.stderr)

    return exit_code


def build_parser() -> argparse.ArgumentParser:
    """Build the adapter-only parser used by the Docker entrypoint."""

    parser = argparse.ArgumentParser(prog="previewshield-action")
    parser.add_argument("--target", default="")
    parser.add_argument("--baseline", default="")
    parser.add_argument("--preview", default="")
    parser.add_argument("--config", default="")
    parser.add_argument("--paths", default="")
    parser.add_argument("--fail-on", default="high")
    parser.add_argument("--format", default="json", dest="report_format")
    parser.add_argument("--output", default="")
    parser.add_argument("--allow-private", default="false")
    return parser


def parse_action_args(argv: Sequence[str]) -> ActionInputs:
    """Parse fixed action metadata arguments into validated inputs."""

    namespace = build_parser().parse_args(argv)
    return ActionInputs.from_values(
        target=cast(str, namespace.target),
        baseline=cast(str, namespace.baseline),
        preview=cast(str, namespace.preview),
        config=cast(str, namespace.config),
        paths=cast(str, namespace.paths),
        fail_on=cast(str, namespace.fail_on),
        report_format=cast(str, namespace.report_format),
        output=cast(str, namespace.output),
        allow_private=cast(str, namespace.allow_private),
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Run the Docker action from fixed arguments, with ``INPUT_*`` as fallback."""

    raw_arguments = list(sys.argv[1:] if argv is None else argv)
    try:
        inputs = (
            parse_action_args(raw_arguments)
            if raw_arguments
            else ActionInputs.from_environment(os.environ)
        )
    except ActionInputError as error:
        print(f"PreviewShield action input error: {error}", file=sys.stderr)
        return ACTION_USAGE_ERROR
    return run_action(inputs)


if __name__ == "__main__":
    raise SystemExit(main())
